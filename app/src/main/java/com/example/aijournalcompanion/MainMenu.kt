/**
 * Main menu: the home screen. Each card explains what it does,
 * so users always know where to go next.
 */
@Composable
fun MainMenu(
    onNavigate: (AppScreen) -> Unit,
    onHelp: () -> Unit,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 24.dp, vertical = 16.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        // App logo
        Surface(
            shape = CircleShape,
            color = MaterialTheme.colorScheme.primaryContainer,
            modifier = Modifier.size(84.dp)
        ) {
            Box(contentAlignment = Alignment.Center) {
                Text("🌿", fontSize = 40.sp)
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        Text(
            text = "AI Journal Companion",
            style = MaterialTheme.typography.headlineLarge,
            color = MaterialTheme.colorScheme.onBackground,
            textAlign = TextAlign.Center
        )
        Text(
            text = "Reflect on your day and get gentle AI feedback.",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
            modifier = Modifier.padding(top = 6.dp, bottom = 28.dp)
        )

        MenuCard(
            emoji = "✍️",
            title = "New Journal Entry",
            subtitle = "Write your thoughts and get emotion + advice",
            onClick = { onNavigate(AppScreen.JOURNAL) }
        )
        MenuCard(
            emoji = "📚",
            title = "View History",
            subtitle = "Sort, search and drag entries to delete",
            onClick = { onNavigate(AppScreen.HISTORY) }
        )
        MenuCard(
            emoji = "📊",
            title = "Emotion Insights",
            subtitle = "See your emotions as a pie chart",
            onClick = { onNavigate(AppScreen.INSIGHTS) }
        )

        Spacer(modifier = Modifier.height(12.dp))

        SecondaryButton(
            text = "Help Guide",
            onClick = onHelp,
            icon = Icons.Filled.Info,
            modifier = Modifier.fillMaxWidth()
        )
    }
}

/** A tappable card with an emoji, title, short description and arrow. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun MenuCard(
    emoji: String,
    title: String,
    subtitle: String,
    onClick: () -> Unit
) {
    Card(
        onClick = onClick,
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 6.dp),
        shape = MaterialTheme.shapes.medium,
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
    ) {
        Row(
            modifier = Modifier.padding(16.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.Start
        ) {
            Surface(
                shape = MaterialTheme.shapes.small,
                color = MaterialTheme.colorScheme.primaryContainer,
                modifier = Modifier.size(48.dp)
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Text(emoji, fontSize = 22.sp)
                }
            }
            Spacer(modifier = Modifier.width(14.dp))
            Column(modifier = Modifier.weight(1f)) {
                Text(title, style = MaterialTheme.typography.titleMedium)
                Text(
                    subtitle,
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
            Icon(
                Icons.AutoMirrored.Filled.KeyboardArrowRight,
                contentDescription = null,
                tint = MaterialTheme.colorScheme.primary
            )
        }
    }
}
